"""Print a new VAPID key pair for Web Push, ready to paste into Render.

    python scripts/gen_vapid.py

VAPID_PUBLIC_KEY goes to the app (the server hands it out), VAPID_PRIVATE_KEY
stays secret on the server. Generate them once: new keys invalidate every
existing subscription.
"""

import base64

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import ec


def b64(data: bytes) -> str:
    return base64.urlsafe_b64encode(data).rstrip(b"=").decode()


key = ec.generate_private_key(ec.SECP256R1())
private = key.private_numbers().private_value.to_bytes(32, "big")
public = key.public_key().public_bytes(serialization.Encoding.X962, serialization.PublicFormat.UncompressedPoint)
print(f"VAPID_PUBLIC_KEY={b64(public)}")
print(f"VAPID_PRIVATE_KEY={b64(private)}")
