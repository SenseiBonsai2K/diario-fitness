# Appearance: a neutral background (light, grey, dark, black) and an accent colour,
# chosen separately. Generates src/themes.css + src/lib/themes.js and checks that
# every background × accent combination keeps text contrast at 4.5:1 or more.
# Usage: python3 scripts/gen-themes.py src/themes.css src/lib/themes.js
import json, sys

def hx(h): h = h.lstrip('#'); return tuple(int(h[i:i+2], 16) for i in (0, 2, 4))
def lum(c):
    def ch(v):
        v /= 255; return v / 12.92 if v <= 0.03928 else ((v + 0.055) / 1.055) ** 2.4
    r, g, b = map(ch, c); return 0.2126 * r + 0.7152 * g + 0.0722 * b
def cr(a, b):
    la, lb = lum(hx(a)), lum(hx(b)); la, lb = max(la, lb), min(la, lb); return (la + 0.05) / (lb + 0.05)
def mix(a, b, t):
    A, B = hx(a), hx(b); return "#" + "".join(f"{round(A[i]*(1-t)+B[i]*t):02X}" for i in range(3))
def trip(h): return " ".join(map(str, hx(h)))

# Neutral backgrounds. mode = which accent variant they use.
BGS = {
  "light": dict(mode="light", bg="#F4F4F5", surface="#FFFFFF", raised="#ECECEE", line="#DCDCE0", ink="#18181B", muted="#5B5B66", hero="#1C1C22"),
  "grey":  dict(mode="light", bg="#E4E5E8", surface="#F7F7F8", raised="#DADBDF", line="#CBCCD1", ink="#18181B", muted="#4F4F59", hero="#202027"),
  "dark":  dict(mode="dark",  bg="#141416", surface="#1D1D21", raised="#27272C", line="#33333A", ink="#ECECEF", muted="#9C9CA6", hero="#2A2A31"),
  "black": dict(mode="dark",  bg="#000000", surface="#111113", raised="#1B1B1E", line="#2A2A2F", ink="#EDEDF0", muted="#9A9AA3", hero="#1E1E23"),
}

# Accents: one variant for light backgrounds, one for dark ones; heroAccent sits on the dark hero card.
ACCENTS = {
  "blue":      dict(light=("#2B4FCF", "#FFFFFF", "#E3E8FA"), dark=("#8EA6FF", "#0E1430", "#232B47"), hero="#A8BEFF"),
  "teal":      dict(light=("#0B6E6E", "#FFFFFF", "#D7EEEC"), dark=("#4FD1C5", "#032321", "#183634"), hero="#7FE0D6"),
  "lime":      dict(light=("#3F6A12", "#FFFFFF", "#E3EFD3"), dark=("#B5E85A", "#1A2604", "#2A3A18"), hero="#C4F06A"),
  "violet":    dict(light=("#6236C9", "#FFFFFF", "#ECE4FB"), dark=("#B49BFF", "#1D0F45", "#2E2550"), hero="#C7B2FF"),
  "raspberry": dict(light=("#B0265A", "#FFFFFF", "#F9E0E9"), dark=("#FF7FAE", "#3A0619", "#43202E"), hero="#FFA6C6"),
  "orange":    dict(light=("#A23F06", "#FFFFFF", "#FCE7D6"), dark=("#FF9A3D", "#2B1300", "#3A2716"), hero="#FFB066"),
  "amber":     dict(light=("#8A5A00", "#FFFFFF", "#F8EBCB"), dark=("#F5C04A", "#2B1F00", "#3A2E12"), hero="#FFD37A"),
  "mono":      dict(light=("#2F2F36", "#FFFFFF", "#E4E4E8"), dark=("#E4E4E8", "#111113", "#2C2C33"), hero="#F2F2F5"),
}

# Vivid accents: start from a saturated colour and let the script find the brightest
# variant that still reads as text — darkened just enough on light backgrounds,
# kept bright (neon) on dark ones. Ink on the accent is black or white, whichever reads better.
VIVID = {
  "red":      "#FF2D46",
  "fuchsia":  "#FF2DB4",
  "electric": "#2F6BFF",
  "cyan":     "#00D4FF",
  "neon":     "#2BFF88",
  "yellow":   "#FFE01A",
  "fluo":     "#FF6A00",
  "purple":   "#A855FF",
}
def tune(base, against, toward, min_=4.5):
    for i in range(0, 101):
        c = mix(base, toward, i / 100)
        if all(cr(c, x) >= min_ for x in against): return c
    raise SystemExit(f"cannot tune {base}")
def best_ink(c): return "#FFFFFF" if cr("#FFFFFF", c) >= cr("#0A0A0C", c) else "#0A0A0C"
LIGHT_BGS = [v for v in BGS.values() if v["mode"] == "light"]
DARK_BGS = [v for v in BGS.values() if v["mode"] == "dark"]
for name, base in VIVID.items():
    lt = tune(base, [x for b in LIGHT_BGS for x in (b["bg"], b["surface"])], "#000000")
    dk = tune(base, [x for b in DARK_BGS for x in (b["bg"], b["surface"])], "#FFFFFF")
    hero = tune(base, [b["hero"] for b in BGS.values()], "#FFFFFF")
    lsoft = mix(lt, "#FFFFFF", 0.86)
    while cr(lt, lsoft) < 4.5: lsoft = mix(lsoft, "#FFFFFF", 0.3)
    dsoft = mix(dk, "#141416", 0.78)
    while cr(dk, dsoft) < 4.5: dsoft = mix(dsoft, "#000000", 0.3)
    ACCENTS[name] = dict(light=(lt, best_ink(lt), lsoft), dark=(dk, best_ink(dk), dsoft), hero=hero, vivid=True)

ok = True
def need(label, a, b, min_=4.5):
    global ok
    r = cr(a, b)
    if r < min_: ok = False; print("FAIL", label, round(r, 2))

for bn, b in BGS.items():
    need(f"{bn} ink/bg", b["ink"], b["bg"]); need(f"{bn} muted/surface", b["muted"], b["surface"]); need(f"{bn} muted/bg", b["muted"], b["bg"])
    need(f"{bn} muted/raised", b["muted"], b["raised"])
    for an, a in ACCENTS.items():
        acc, ink, soft = a[b["mode"]]
        need(f"{bn}+{an} accent/surface", acc, b["surface"]); need(f"{bn}+{an} accent/bg", acc, b["bg"])
        need(f"{bn}+{an} accentInk/accent", ink, acc); need(f"{bn}+{an} accent/soft", acc, soft)
        need(f"{bn}+{an} heroAccent/hero", a["hero"], b["hero"]); need(f"{bn}+{an} hero/heroAccent", b["hero"], a["hero"])
        need(f"{bn}+{an} heroMuted/hero", mix("#F4F6FC", a["hero"], 0.45), b["hero"])

css = ["/* Generated by scripts/gen-themes.py: neutral backgrounds × accent colours. */",
  ':root[data-mode="light"] {\n  --good: 31 122 77;\n  --warn: 163 98 10;\n  --bad: 179 54 43;\n  --shadow: 20 30 60;\n}',
  ':root[data-mode="dark"] {\n  --good: 92 192 140;\n  --warn: 224 165 74;\n  --bad: 239 123 112;\n  --shadow: 0 0 0;\n}']
for bn, b in BGS.items():
    css.append(f':root[data-bg="{bn}"] {{\n' + "".join(f"  --{k}: {trip(b[k])};\n" for k in ["bg", "surface", "raised", "line", "ink", "muted", "hero"]) + f"  color-scheme: {b['mode']};\n}}")
for an, a in ACCENTS.items():
    for mode in ["light", "dark"]:
        acc, ink, soft = a[mode]
        css.append(f':root[data-mode="{mode}"][data-accent="{an}"] {{\n  --accent: {trip(acc)};\n  --accent-ink: {trip(ink)};\n  --accent-soft: {trip(soft)};\n  --hero-accent: {trip(a["hero"])};\n  --hero-muted: {trip(mix("#F4F6FC", a["hero"], 0.45))};\n}}')
open(sys.argv[1], "w").write("\n".join(css) + "\n")

meta = {
  "backgrounds": {k: {"mode": v["mode"], "bg": v["bg"], "surface": v["surface"], "line": v["line"]} for k, v in BGS.items()},
  "accents": {k: {"light": v["light"][0], "dark": v["dark"][0], "vivid": bool(v.get("vivid"))} for k, v in ACCENTS.items()},
}
open(sys.argv[2], "w").write("// Generated by scripts/gen-themes.py: swatches for the pickers and the browser bar.\nexport const APPEARANCE = " + json.dumps(meta, indent=2) + ";\n")
print("ALL OK" if ok else "SOME FAIL")
sys.exit(0 if ok else 1)
